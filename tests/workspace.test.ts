import assert from 'node:assert/strict';
import { makeItems, parseItems, itemsCsv } from '../src/utils/workspace.ts';
const task=makeItems('company','Prepare onboarding','Ahsan','2026-11-01','task-1');
assert.equal(task.length,1);
assert.equal(task[0].owner,'Ahsan');
assert.equal(task[0].date,'2026-11-01');
assert.equal(task[0].status,'To do');
task[0].status='Done';task[0].body='Checklist ready';
assert.deepEqual(parseItems(JSON.stringify(task)),task,'edited task survives storage roundtrip');
const drafts=makeItems('social','coffee subscription','Instagram','2026-11-02','post');
assert.equal(drafts.length,3);
assert(drafts.every(x=>x.body.includes('coffee subscription')&&x.status==='Draft'&&x.owner==='Instagram'));
assert.equal(new Set(drafts.map(x=>x.id)).size,3);
assert.equal(makeItems('company','  ','','','id').length,0);
assert.equal(parseItems(JSON.stringify([...task,...task,{...task[0],id:'bad',status:'Published'}])).length,1);
assert.throws(()=>parseItems('{bad JSON'));
assert.equal(parseItems(JSON.stringify(Array.from({length:110},(_,i)=>({...task[0],id:String(i)})))).length,100);
const csv=itemsCsv([{...task[0],title:'=1+2',body:'A "quote", and\na line'}]);
assert(csv.includes('"\'=1+2"'));
assert(csv.includes('"A ""quote"", and\na line"'));
assert(csv.includes('"Done"'));
console.log('Workspace checks passed: task updates, saved-state restoration, content drafts, validation, CSV escaping and formula protection.');
